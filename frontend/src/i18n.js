const I18nContext = createContext(null);

function formatTemplate(input, vars = {}) {
  return input.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ""));
}

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem("qpp_lang") || "en");

  useEffect(() => {
    localStorage.setItem("qpp_lang", lang);
    document.documentElement.setAttribute("lang", lang);
  }, [lang]);

  const value = useMemo(() => {
    const current = { ...dictionary.en, ...(dictionary[lang] || {}) };
    return {
      lang,
      setLang,
      t: (key, vars) => formatTemplate(current[key] || key, vars),
    };
  }, [lang]);

  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within LanguageProvider");
  return context;
}
